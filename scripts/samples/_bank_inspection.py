def resolve_numeric(ci: CI, params: dict) -> CI:
    """設備パラメータ（中心値・範囲）を実値に置き換えた CI を返す。"""
    if ci.kind != "num":
        return ci
    upd = {}
    if ci.cp:
        c = params[ci.cp]
        upd.update(lo=c - ci.tol, hi=c + ci.tol, mean=c, center=c, cp=None)
    if isinstance(ci.lo, str):
        upd["lo"] = params[ci.lo]
    if isinstance(ci.mean, str):
        upd["mean"] = params[ci.mean]
    return replace(ci, **upd) if upd else ci
