"""F4 設備点検・保全作業報告書用: 設備種別ごとの点検項目（チェックシート）と定期交換部品の定義。

点検項目 CI の主なフィールド:
    zone / item : 点検部位・点検項目（{car} {pn} {fan} {lp} {shelf} は号車・号機ごとに展開、{sv} などは設備パラメータ）
    kind        : "num"（測定値）/ "vis"（目視）/ "func"（動作確認）
    sub         : domain のサブシステム名（トラブル履歴・部品との対応付けに使う）
    cyc         : 点検周期（月）。月例=1、3ヶ月=3、6ヶ月=6、年次=12。周期レベル以下の項目を点検する
    lo / hi     : 管理値の下限・上限（None は片側）。cp があれば設備パラメータを中心に ±tol
    mean / sd   : 正常時の測定値の分布。drift=+1 は使用とともに増える（上限側へ劣化）、-1 は減る
    kw          : トラブル報告の文中から測定値を拾うためのキーワード
    part / qty  : 不良時・定期交換で交換する部品（domain の部品カタログ名）
    ok/tri/ng   : 目視・動作確認の記入文（良 / 要観察 / 不良）
    ok_act ...  : 処置欄の記入候補
    only        : 設備名・型式・工程に含まれる語で対象設備を絞る（"|" 区切り）
    grp         : v2 の左右の表の振り分け（A=機構部・プロセス部 / B=電装・安全・ユーティリティ）

測定値の管理値は domain のトラブルシナリオの値（通常値・異常値）と矛盾しないように決めている。
例: ドライポンプ電流は通常 5.5〜7.5A・異常時 9〜18A なので上限 9.0A。
"""
from __future__ import annotations

from dataclasses import dataclass, replace


@dataclass(frozen=True)
class CI:
    zone: str
    item: str
    kind: str
    sub: str
    cyc: int = 1
    lo: float | None = None
    hi: float | None = None
    unit: str = ""
    mean: float = 0.0
    sd: float = 0.0
    nd: int = 1
    snd: int | None = None        # 基準値の小数桁（省略時は nd）
    center: float | None = None   # 「中心±公差」表記にする場合の中心値
    cp: str | None = None         # 中心値を設備パラメータから取る
    tol: float = 0.0
    drift: int = 0
    kw: tuple = ()
    part: str | None = None
    qty: tuple = (1, 1)
    std: str | None = None
    ok: tuple = ()
    tri: tuple = ()
    ng: tuple = ()
    ok_act: tuple = ()
    ok_p: float = 0.0
    tri_act: tuple = ()
    ng_act: tuple = ()
    only: str = ""
    grp: str = "A"
    minv: float | None = None
    sci: bool = False
    season: bool = False          # 夏場に値が上がる（温度系）


def N(zone, item, sub, lo, hi, unit, mean, sd, nd=1, **kw) -> CI:
    """測定値の項目（片側・両側の範囲）。"""
    return CI(zone, item, "num", sub, lo=lo, hi=hi, unit=unit, mean=mean, sd=sd, nd=nd, **kw)


def C(zone, item, sub, center, tol, unit, sd, nd=1, **kw) -> CI:
    """測定値の項目（中心±公差）。center が str なら設備パラメータ名。"""
    if isinstance(center, str):
        return CI(zone, item, "num", sub, unit=unit, sd=sd, nd=nd, cp=center, tol=tol, **kw)
    return CI(zone, item, "num", sub, lo=center - tol, hi=center + tol, unit=unit, mean=center, sd=sd, nd=nd,
              center=center, tol=tol, **kw)


def V(zone, item, sub, **kw) -> CI:
    kw.setdefault("std", "異常なきこと")
    kw.setdefault("ok", ("異常なし", "良", "なし"))
    return CI(zone, item, "vis", sub, **kw)


def F(zone, item, sub, **kw) -> CI:
    kw.setdefault("std", "正常に動作すること")
    kw.setdefault("ok", ("良好", "OK", "正常"))
    return CI(zone, item, "func", sub, **kw)


