def _p_slurry(r):
    sv = r.choice([150, 180, 200, 220, 250])
    # fd（フィルタ使用日数）は domain の使用量カウンタ（前回交換からの経過日数）で上書きする
    return dict(sv=sv, pv=int(sv * r.uniform(0.45, 0.86)), dp=fx(r, 0.08, 0.24, 2), pp=fx(r, 0.22, 0.38, 2),
                fd=r.randint(18, 78), fl=r.choice([10, 15, 20, 30]), rr=r.randint(5, 22), pl=r.randint(1, 2),
                nfd=r.choice([14, 20, 21]), slr=r.choice(["SiO2系", "セリア系", "W用", "Cu用"]))


def _p_pad(r):
    # used（パッド使用枚数）と life（寿命設定）、gd（残溝）は domain 側で設備ごとのカウンタ・設定値に置き換える
    life = r.choice([900, 1000, 1100, 1200])
    scl = r.randint(3, 60)
    return dict(life=life, used=life + r.randint(-120, 40), gd=fx(r, 0.12, 0.38, 2), gd0=fx(r, 0.70, 0.80, 2),
                sc=r.randint(max(12, scl * 2), max(380, scl * 6)),   # 「多発」なので通常値（scl）の2倍以上
                scl=scl, pl=r.randint(1, 2), bub=r.randint(1, 4),
                amp=fx(r, 8.5, 14.0), amp0=fx(r, 5.5, 7.5),
                dn=r.randint(max(0, scl // 5), scl - 1))          # 交換後の欠陥検査の実測値（管理値 scl 未満）


